CREATE TABLE IF NOT EXISTS public.books (
 book_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(200) NOT NULL, author VARCHAR(150) NOT NULL,
 isbn VARCHAR(20) NOT NULL UNIQUE, price NUMERIC(10,2) NOT NULL CHECK(price>=0),
 published_year INTEGER, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.book_import_errors (
 error_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 import_file TEXT NOT NULL, source_row_number BIGINT,
 raw_title TEXT, raw_author TEXT, raw_isbn TEXT, raw_price TEXT,
 raw_published_year TEXT, error_reason TEXT NOT NULL,
 logged_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
